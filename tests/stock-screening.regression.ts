import assert from "node:assert/strict";
import { analyzeStock, parseDailyBars, type DailyBar } from "../server/services/stock-screening";
const now = Date.parse("2026-10-13T10:00:00Z");
const bars: DailyBar[] = Array.from({ length: 60 }, (_, index) => ({ time: Math.floor(now / 1000) - (60 - index) * 86400, open: 100, high: 102, low: 98, close: 100, volume: 20_000_000 }));
const flat = analyzeStock("BBCA.JK", "Example", bars, now);
assert.equal(flat.rsi, 50);
assert.equal(flat.cmf, 0);
assert.equal(flat.relativeVolume, 1);
assert.equal(flat.support, 98);
assert.equal(flat.resistance, 102);
assert.deepEqual(flat.signals, []);
const breakout = [...bars.slice(0, -1), { ...bars.at(-1)!, high: 111, close: 110, volume: 40_000_000 }];
const result = analyzeStock("BBCA", "Example", breakout, now);
assert.ok(result.signals.includes("Breakout bervolume"));
assert.equal(result.resistance, 102); // Excludes the breakout candle.
assert.equal(result.invalidation, 102);
assert.equal(result.relativeVolume, 2);
assert.ok(result.risks.some((risk) => risk.includes("RSI")));
assert.deepEqual(analyzeStock("X", "X", breakout.map((bar) => ({ ...bar, volume: 10 })), now).signals, []);
assert.deepEqual(analyzeStock("X", "X", breakout, now + 10 * 86400000).signals, []);
assert.throws(() => analyzeStock("X", "X", bars.slice(0, 50), now));
const accumulation = bars.map((bar, index) => ({ ...bar, close: index >= 55 ? 100.5 + (index - 55) * 0.1 : 100.5, volume: index >= 55 ? 40_000_000 : bar.volume }));
assert.ok(analyzeStock("X", "X", accumulation, now).signals.includes("Indikasi akumulasi"));
const distribution = bars.map((bar, index) => ({ ...bar, close: index >= 55 ? 99.5 - (index - 55) * 0.1 : 99.5 }));
assert.ok(analyzeStock("X", "X", distribution, now).risks.some((risk) => risk.includes("tekanan jual")));
const today = Math.floor(Date.parse("2026-10-13T02:00:00Z") / 1000);
const raw = { timestamp: [today - 86400, today, today + 86400], indicators: { quote: [{ open: [100, 100, null], high: [102, 102, null], low: [98, 98, null], close: [101, 101, null], volume: [100, 100, null] }] } };
assert.equal(parseDailyBars(raw, Date.parse("2026-10-13T08:00:00Z")).length, 1);
assert.equal(parseDailyBars(raw, Date.parse("2026-10-13T10:00:00Z")).length, 2);
assert.equal(parseDailyBars({ ...raw, indicators: { quote: [{ open: [100], high: [90], low: [98], close: [101], volume: [100] }] } }, now).length, 0);
console.log("PASS: breakout against prior resistance, volume baseline excludes current session, accumulation/distribution, liquidity and stale-data exclusions, flat RSI, insufficient history, partial sessions and invalid OHLC");
